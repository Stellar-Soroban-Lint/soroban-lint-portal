#!/usr/bin/env node
/**
 * Generate the rule catalog at build time from the released CLI.
 *
 * `/rules` and `/rules/[id]` document the rules. If that text were written by
 * hand it would drift from the code the moment a rule's severity or stability
 * changed, and nobody would notice until the site lied. So the catalog is
 * generated from `soroban-lint rules --format json` — the same command the CLI
 * exposes to users — and the build fails if any required field is missing or
 * malformed. A rule that cannot be documented cannot ship.
 *
 * Output: `src/generated/rule-catalog.ts` and `src/generated/rule-catalog.json`.
 *
 * Usage: node scripts/generate-rule-catalog.mjs
 */

import { spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = join(ROOT, "src", "generated");

const SEVERITIES = ["error", "warning", "info"];
const CONFIDENCES = ["high", "medium", "low"];
const STABILITIES = ["stable", "experimental"];

/** Fields every rule must carry, with the values each may take. */
const REQUIRED = {
  id: (value) => /^SL\d{3}$/.test(value),
  name: (value) => typeof value === "string" && value.length > 0,
  description: (value) => typeof value === "string" && value.length > 0,
  rationale: (value) => typeof value === "string" && value.length > 0,
  limitations: (value) => typeof value === "string" && value.length > 0,
  default_severity: (value) => SEVERITIES.includes(value),
  default_confidence: (value) => CONFIDENCES.includes(value),
  stability: (value) => STABILITIES.includes(value),
};

function nativeCli() {
  const candidates = [
    process.env.SOROBAN_LINT_BIN,
    resolve(ROOT, "..", "soroban-lint-core", "target", "release", "soroban-lint"),
    resolve(ROOT, "..", "soroban-lint-core", "target", "debug", "soroban-lint"),
  ].filter(Boolean);

  for (const candidate of candidates) {
    const probe = spawnSync(candidate, ["rules", "--format", "json"], { encoding: "utf8" });
    if (!probe.error && probe.status === 0) {
      return { binary: candidate, stdout: probe.stdout };
    }
  }

  throw new Error(
    [
      "cannot generate the rule catalog: no working soroban-lint binary.",
      "",
      "Set SOROBAN_LINT_BIN to a soroban-lint executable, or build one:",
      "  cargo build --release -p soroban-lint-cli    # in ../soroban-lint-core",
      "",
      "The /rules pages are generated from `soroban-lint rules --format json`,",
      "so this command runs on every build and on CI. Building the catalog from",
      "a hand-maintained copy of the metadata would let the docs drift from the",
      "binary, which is the failure this script exists to prevent.",
    ].join("\n"),
  );
}

/** Fail loudly, naming the offending rule and field. */
function validate(rules) {
  const problems = [];

  for (const rule of rules) {
    const where = typeof rule?.id === "string" ? rule.id : JSON.stringify(rule);
    for (const [field, check] of Object.entries(REQUIRED)) {
      if (!(field in rule)) {
        problems.push(`${where}: missing required field \`${field}\``);
      } else if (!check(rule[field])) {
        problems.push(`${where}: field \`${field}\` has an unusable value ${JSON.stringify(rule[field])}`);
      }
    }
  }

  const ids = rules.map((rule) => rule.id);
  const duplicates = ids.filter((id, index) => ids.indexOf(id) !== index);
  for (const id of new Set(duplicates)) {
    problems.push(`duplicate rule id \`${id}\`: rule ids are permanent and must be unique`);
  }

  if (problems.length > 0) {
    throw new Error(
      `the rule catalog from \`soroban-lint rules --format json\` is unusable:\n  ${problems.join("\n  ")}`,
    );
  }
}

const { binary, stdout } = nativeCli();
const parsed = JSON.parse(stdout);

if (!Array.isArray(parsed.rules) || parsed.rules.length === 0) {
  throw new Error("`soroban-lint rules --format json` returned no rules");
}

const rules = [...parsed.rules].sort((a, b) => a.id.localeCompare(b.id));
validate(rules);

// Emit only the fields the pages use, in a fixed order, so the committed file
// has a stable diff.
const ordered = rules.map((rule) => ({
  id: rule.id,
  name: rule.name,
  description: rule.description,
  rationale: rule.rationale,
  limitations: rule.limitations,
  default_severity: rule.default_severity,
  default_confidence: rule.default_confidence,
  stability: rule.stability,
}));

mkdirSync(OUT_DIR, { recursive: true });

writeFileSync(
  join(OUT_DIR, "rule-catalog.json"),
  `${JSON.stringify({ version: parsed.version, rules: ordered }, null, 2)}\n`,
);

writeFileSync(
  join(OUT_DIR, "rule-catalog.ts"),
  `// Generated by scripts/generate-rule-catalog.mjs. Do not edit.
//
// Source: \`soroban-lint rules --format json\`
// Binary:  ${relative(ROOT, binary)}
//
// Regenerating on every build is what keeps the /rules pages honest: the
// documentation cannot describe a rule the binary does not have.

import type { RuleMeta } from "@/lib/rules";

export const RULE_CATALOG_SCHEMA_VERSION = ${JSON.stringify(Number(parsed.version))};

export const RULES: readonly RuleMeta[] = ${JSON.stringify(ordered, null, 2)} as const;
`,
);

const stable = ordered.filter((rule) => rule.stability === "stable").length;
console.log(
  `rule catalog: ${ordered.length} rules (${stable} stable, ${ordered.length - stable} experimental) from ${relative(ROOT, binary)}`,
);